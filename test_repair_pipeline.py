"""End-to-end tests for the repair sequence, against known-correct answers.

Separate from `test_repairer.py`, which tests the sequence's *structure* with
step 4 stubbed out. This runs the real tools on real defective meshes and asks
whether the output is **right**, not whether the machinery ran.

**Every expected value comes from the control, not from what the code does
today.** The fixtures are one perfect 760-face sphere with one defect injected
into each, so the correct answer is known in advance: `sphere_correct` is 760
faces at +4094.9, and every repair should land there. A suite that asserted the
current behaviour instead would have locked in the `inverted_third` bug below.

That distinction is not theoretical. Three meshes in this project have passed
non-manifold, open-edge, degenerate, seam, shell *and* volume-magnitude checks
while being visibly wrong, and one of them is here: `sphere_inverted_third`
comes out of the pipeline as a flawless sphere that is inside-out.

**Volume is signed and compared against the control's +4094.9**, never against
the input. A ratio to the input is meaningless when the input is the thing that
was broken — `doubles` legitimately halves, `seam` legitimately gains, and an
inverted mesh legitimately changes sign.

Fixtures live in `tests/probes/` and are regenerated by
`tools/make_probe_meshes.py` if missing, so the suite is self-contained.
"""

import os
import subprocess
import sys
import unittest

from libs import mesh_io, repairer, scanner

HERE = os.path.dirname(os.path.abspath(__file__))
PROBES = os.path.join(HERE, 'tests', 'probes')
GENERATOR = os.path.join(HERE, 'tools', 'make_probe_meshes.py')

#: The control's signed volume. Every fixture is that sphere plus one defect,
#: so this is what a correct repair must reconstruct.
CONTROL_VOLUME = 4094.9

#: The control's face count.
CONTROL_FACES = 760

#: How close a repaired volume must sit to the control, as a fraction.
#: Generous: a repair that removes a fin or a degenerate face changes the
#: volume in the fifth significant figure, and the point of the check is to
#: catch a mesh that is half-missing or inside-out, not to measure rounding.
VOLUME_TOLERANCE = 0.005

FIXTURES = ('correct', 'degenerate', 'tjunction', 'tjunction_many', 'fin',
            'doubles', 'inverted', 'inverted_third', 'seam', 'allbad')

HAVE_TOOLS = repairer.is_available()


def load(name):
    path = os.path.join(PROBES, f'sphere_{name}.stl')
    return mesh_io.load(mesh_io.probe(path, '/tmp/unused_destination.stl'))


@unittest.skipUnless(HAVE_TOOLS, "pymeshlab and pymeshfix are both needed")
class ProbeCase(unittest.TestCase):
    """Base: ensures the fixtures exist before anything runs."""

    @classmethod
    def setUpClass(cls):
        missing = [n for n in FIXTURES
                   if not os.path.exists(
                       os.path.join(PROBES, f'sphere_{n}.stl'))]
        if missing:
            # Regenerate rather than skip: the generator is committed and the
            # meshes are derived, so a missing file is a stale checkout, not a
            # reason to report success without testing anything.
            subprocess.run([sys.executable, GENERATOR, PROBES],
                           check=True, capture_output=True)

    def assertVolumeMatchesControl(self, mesh, msg=''):
        """Signed volume within tolerance of the control's +4094.9.

        Signed on purpose. An inside-out mesh has the right magnitude and the
        wrong sign, and it is identical to a correct one on every other check
        this project has.
        """
        volume = scanner.volume(mesh)
        delta = abs(volume - CONTROL_VOLUME) / CONTROL_VOLUME
        self.assertLess(
            delta, VOLUME_TOLERANCE,
            f"{msg}volume {volume:+.1f} is not the control's "
            f"{CONTROL_VOLUME:+.1f} ({delta * 100:.2f}% off)")

    def assertRepairsToControl(self, name, faces=CONTROL_FACES,
                               max_lost=0, face_tolerance=0):
        """The whole assertion for one fixture: clean, and geometrically right.

        `faces` is the expected output count, `max_lost` how many input
        vertices may legitimately disappear (a fin's apex may; a point on the
        sound surface may not).
        """
        result = repairer.repair(load(name))
        self.assertTrue(result.ok, f"{name}: {result.problem}")
        scan = scanner.scan(result.mesh)
        self.assertEqual(scan.non_manifold, 0, f"{name}: non-manifold edges")
        self.assertEqual(scan.open_edges, 0, f"{name}: open edges")
        self.assertEqual(scan.degenerate, 0, f"{name}: degenerate faces")
        self.assertLessEqual(
            abs(len(result.mesh.geometry.faces) - faces), face_tolerance,
            f"{name}: {len(result.mesh.geometry.faces)} faces, expected "
            f"{faces} (+/-{face_tolerance})")
        self.assertLessEqual(result.lost_vertices, max_lost,
                             f"{name}: lost {result.lost_vertices} vertices")
        self.assertVolumeMatchesControl(result.mesh, f"{name}: ")
        return result


class TestTheFixturesThemselves(ProbeCase):
    """Guards on the inputs. A fixture that lost its defect tests nothing."""

    def test_the_control_is_what_the_constants_say(self):
        mesh = load('correct')
        self.assertEqual(len(mesh.geometry.faces), CONTROL_FACES)
        self.assertVolumeMatchesControl(mesh)
        self.assertTrue(scanner.scan(mesh).is_clean)

    def test_each_fixture_differs_from_the_control(self):
        """Every probe must actually carry its defect."""
        control = load('correct')
        reference = (scanner.volume(control), len(control.geometry.faces),
                     scanner.scan(control))
        for name in FIXTURES:
            if name == 'correct':
                continue
            with self.subTest(fixture=name):
                mesh = load(name)
                actual = (scanner.volume(mesh), len(mesh.geometry.faces),
                          scanner.scan(mesh))
                self.assertNotEqual(actual, reference,
                                    f"{name} is indistinguishable from the "
                                    f"control — the defect did not survive")

    def test_inverted_is_invisible_to_every_check_but_volume(self):
        """The reason `scanner.volume` exists. A wholly inverted sphere is
        identical to a correct one on nm, open, degenerate and shell count."""
        mesh = load('inverted')
        self.assertTrue(scanner.scan(mesh).is_clean)
        self.assertEqual(len(mesh.geometry.faces), CONTROL_FACES)
        self.assertLess(scanner.volume(mesh), 0)

    def test_inverted_third_keeps_a_positive_total(self):
        """Why the orientation guard cannot see it: a minority of reversed
        faces leaves the signed total positive (+1364.4), so `volume < 0` is
        False and the guard skips a mesh that badly needs it."""
        mesh = load('inverted_third')
        self.assertGreater(scanner.volume(mesh), 0)
        self.assertTrue(scanner.scan(mesh).is_clean)


class TestRepairsToControl(ProbeCase):
    """Each defect, repaired, must reconstruct the control."""

    def test_a_clean_mesh_is_not_damaged(self):
        """The most important row. A pipeline that improves broken meshes and
        quietly degrades good ones is worse than none."""
        self.assertRepairsToControl('correct')

    def test_degenerate(self):
        self.assertRepairsToControl('degenerate')

    def test_one_tjunction(self):
        """Splitting the neighbouring face costs exactly one face and loses
        nothing — the property that distinguishes welder from hole-closing."""
        self.assertRepairsToControl('tjunction', faces=762)

    def test_many_tjunctions(self):
        """150 junctions: 910 faces in, 1,060 out, no vertex lost. A
        commercial repair service reached the same 1,060 independently."""
        self.assertRepairsToControl('tjunction_many', faces=1060)

    def test_fin(self):
        """A fin hangs off one non-manifold edge, so removing it legitimately
        removes its apex — the one vertex loss this suite permits."""
        self.assertRepairsToControl('fin', faces=CONTROL_FACES, max_lost=3,
                                    face_tolerance=6)

    def test_doubles(self):
        """Two coincident spheres become one. The volume halves against the
        input and matches the control, which is why the control is the
        reference and the input is not."""
        self.assertRepairsToControl('doubles')

    def test_wholly_inverted(self):
        """`volume < 0` fires and `by_geometry` turns it outward."""
        self.assertRepairsToControl('inverted')

    def test_seam(self):
        """A reversed cap bounded by one closed loop. The orientation guard
        skips it (+2146.2 is positive), but PyMeshFix re-winds it at step 4 —
        measured, all 760 faces in one call."""
        self.assertRepairsToControl('seam')

    def test_everything_at_once(self):
        """Every defect on one sphere, which is the case that exercises the
        step ordering: duplicates must be removed before the split, and the
        mesh oriented before anything acts on it."""
        self.assertRepairsToControl('allbad', faces=CONTROL_FACES,
                                    max_lost=8, face_tolerance=160)

    @unittest.expectedFailure
    def test_a_third_inverted(self):
        """**KNOWN GAP — this is the bug, not the test.**

        A third of the faces reversed, scattered rather than a contiguous cap.
        The pipeline returns a topologically flawless sphere that is
        **inside-out**: 760 faces, nm=0, open=0, volume −4094.9.

        Why every guard misses it:

        - step 2 skips, because the signed total is +1364.4 — positive, since
          the reversed faces are a minority;
        - step 4's per-part guard skips for the same reason: one shell, so the
          part's volume is the whole mesh's;
        - PyMeshFix unifies the winding but picks the **wrong direction**.
          Measured across inversion fractions, only the 1/3 case inverts:
          every 2nd, 4th, 5th and 10th face all come back +4094.9.

        `by_geometry` fixes it completely — run unguarded before PyMeshFix it
        gives +4094.9 — so the repair exists and the *trigger* is what is
        wrong. `winding_seams` reports 722 seam edges in 0 closed loops, so a
        seam-count trigger would catch this where `volume < 0` cannot, and
        unlike `by_seams` it needs no connected reversed region.

        Marked expected-failure rather than deleted or weakened: the gap stays
        visible in every run. Remove the marker when the trigger is fixed.
        """
        self.assertRepairsToControl('inverted_third')


class TestTheSequenceItselfOnRealMeshes(ProbeCase):
    """Properties of the run, not of the output mesh."""

    def test_a_clean_mesh_needs_no_welding(self):
        result = repairer.repair(load('correct'))
        weld = [s for s in result.steps if s.step is repairer.Step.WELD][0]
        self.assertIn('0 junction', weld.detail)

    def test_the_orientation_guard_fires_only_when_inverted(self):
        fires = {}
        for name in ('correct', 'inverted', 'seam', 'inverted_third'):
            result = repairer.repair(load(name))
            step = [s for s in result.steps
                    if s.step is repairer.Step.ORIENT][0]
            fires[name] = 'skipped' not in step.detail
        self.assertEqual(
            fires, {'correct': False, 'inverted': True,
                    'seam': False, 'inverted_third': False},
            "the guard's firing pattern changed — see test_a_third_inverted")

    def test_duplicates_are_gone_before_the_split(self):
        """Measured: splitting first left `doubles` at 200% volume in 2
        shells, because each copy became its own part."""
        result = repairer.repair(load('doubles'))
        clean = [s for s in result.steps if s.step is repairer.Step.CLEAN][0]
        split = [s for s in result.steps if s.step is repairer.Step.SPLIT][0]
        self.assertEqual(clean.faces_out, CONTROL_FACES)
        self.assertEqual(split.faces_in, CONTROL_FACES)
        self.assertEqual(result.parts, 1)

    def test_no_fixture_takes_more_than_one_part_except_doubles(self):
        """Every probe is one sphere, so the split is a no-op — which is what
        makes the per-part orientation guard untestable on this suite."""
        for name in FIXTURES:
            with self.subTest(fixture=name):
                self.assertLessEqual(repairer.repair(load(name)).parts, 2)


if __name__ == '__main__':
    unittest.main(verbosity=2)
